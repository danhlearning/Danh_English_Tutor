const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const allowed = /\.(?:html|css|js|json|webmanifest|woff2?|webp|png|jpe?g|svg|avif|gif|ico|wav|mp3|ogg|m4a|mp4)$/i;
const isText = file => /\.(?:html|css|js|json|webmanifest|svg)$/i.test(file);
const canonical = (data, text) => text ? Buffer.from(data.toString('utf8').replace(/\r\n/g, '\n')) : data;
function build(directory = root) {
  const files = [];
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      if (['tests', 'node_modules'].includes(entry.name) || entry.isSymbolicLink()) continue;
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.isFile() && allowed.test(entry.name)) {
        const text = isText(file), data = canonical(fs.readFileSync(file), text);
        files.push({url: path.relative(directory, file).split(path.sep).join('/'), bytes: data.length, hash: hash(data), ...(text ? {text:true} : {})});
      }
    }
  }
  for (const dir of ['assets', 'shared', 'grade']) walk(path.join(directory, dir));
  for (const entry of fs.readdirSync(directory, {withFileTypes: true})) {
    if (!entry.isFile() || !(/\.html$/.test(entry.name) || ['avatar.jpg', 'manifest.webmanifest'].includes(entry.name))) continue;
    const text = isText(entry.name), data = canonical(fs.readFileSync(path.join(directory, entry.name)), text);
    files.push({url: entry.name, bytes: data.length, hash: hash(data), ...(text ? {text:true} : {})});
  }
  files.sort((a,b) => a.url.localeCompare(b.url, 'en'));
  const version = hash(JSON.stringify(files) + fs.readFileSync(path.join(directory, 'sw.js'), 'utf8').replace(/\r\n/g, '\n')).slice(0, 20);
  return {version, bytes: files.reduce((sum, file) => sum + file.bytes, 0), files};
}
const serialize = catalog => '/* Generated by scripts/build-offline-catalog.cjs. Do not edit. */\nself.DANH_OFFLINE_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n';
if (require.main === module) {
  const catalog = build(), target = path.join(root, 'offline-catalog.js'), source = serialize(catalog);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) {
      console.error('Offline catalog is stale. Run: node scripts/build-offline-catalog.cjs'); process.exitCode = 1;
    } else console.log('Offline catalog matches all deployable files.');
  } else { fs.writeFileSync(target, source); console.log(`${catalog.files.length} files, ${(catalog.bytes / 1024 / 1024).toFixed(1)} MiB; release ${catalog.version}`); }
}
module.exports = {build, serialize, canonical};
